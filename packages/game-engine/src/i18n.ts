/** Get localized card data. Falls back to English (original card data). */
export function getLocalizedCard(cardId: string, locale?: Locale): {
  title: string;
  text: string;
  hostCue: string;
  choices: { id: string; label: string; hint?: string }[];
} {
  const lang = locale ?? currentLocale;
  const card = CARDS.find((c) => c.id === cardId);
  if (!card) {
    return { title: cardId, text: '', hostCue: '', choices: [] };
  }

  if (lang === 'en') {
    return {
      title: card.title,
      text: card.text,
      hostCue: card.hostCue,
      choices: (card.choices ?? []).map((c) => ({
        id: c.id,
        label: c.label,
        hint: c.hint,
      })),
    };
  }

  const ru = CARD_LOCALES_RU[cardId];
  if (!ru) {
    // Fallback to English
    return {
      title: card.title,
      text: card.text,
      hostCue: card.hostCue,
      choices: (card.choices ?? []).map((c) => ({
        id: c.id,
        label: c.label,
        hint: c.hint,
      })),
    };
  }

  return {
    title: ru.title,
    text: ru.text,
    hostCue: ru.hostCue,
    choices: (card.choices ?? []).map((c) => ({
      id: c.id,
      label: ru.choices[c.id]?.label ?? c.label,
      hint: ru.choices[c.id]?.hint ?? c.hint,
    })),
  };
}

