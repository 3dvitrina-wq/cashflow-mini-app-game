const gameEvent = z.object({
  type: z.enum([
    'command_accepted',
    'command_rejected',
    'effect',
    'money',
    'host',
    'phase',
    'settlement',
    'finished',
    'warn',
    'contract',
    'futures',
    'deal',
    'timeline',
    'animation',
    'reaction',
    'audit',
  ]),
  playerId: playerId.optional(),
  effectType: effectType.optional(),
  amount: z.number().optional(),
  cue: z.string().optional(),
  message: z.string().optional(),
  round: z.number().optional(),
  payload: z.record(z.unknown()).optional(),
});

const interestWindow = z.object({
  cardId: z.string(),
  cardTitle: z.string(),
  eligiblePlayers: z.array(playerId),
  interestedPlayers: z.array(playerId),
  selectedPlayers: z.array(playerId),
  openedRound: z.number().int().min(1),
  windowDurationMs: z.number().positive(),
  status: z.enum(['open', 'closed']),
});

const volatility = z.object({
  marketEventFrequency: z.number().min(0).max(1),
  eventSeverityMultiplier: z.number().min(0.5).max(2),
  crisisProbability: z.number().min(0).max(1),
  opportunityBonus: z.number().min(0),
});

export const SimulationMatchStateSchema = z.object({
  id: z.string(),
  seed: z.number().int(),
  rngCounter: z.number().int().min(0),
  phase: z.enum([
    'lobby',
    'market_pulse',
    'settlement',
    'decision',
    'intent_window',
    'resolution',
    'deal_window',
    'draft_select',
    'draft_pick',
    'finished',
  ]),
  round: z.number().int().min(1),
  maxRounds: z.number().int().min(1),
  roomMode: z.enum(['calm', 'normal', 'rollercoaster', 'chaos']),
  communicationMode: z.enum(['reactions_only', 'structured_chat']),
  hostMode: z.enum(['silent', 'template', 'llm_text', 'voice', 'video']),
  timer: z.object({
    turnSeconds: z.union([z.literal(45), z.literal(90), z.literal(180)]),
    waitForAllIntents: z.boolean(),
    autoPassOnTimeout: z.boolean(),
  }),
  epoch: z.object({
    id: z.string(),
    name: z.string(),
    description: z.string(),
    cardPool: z.array(z.string()),
    marketPulseWeights: z.record(z.number()),
    volatility: volatility.optional(),
  }),
  macro: z.object({
    taxRate: z.number().min(0).max(1),
    cryptoPolicy: z.enum(['friendly', 'neutral', 'hostile']),
    employmentFriction: z.number().min(0).max(1),
    migrationCost: z.number().min(0),
    legalProtection: z.number().min(0).max(1),
  }),
  activePlayerIndex: z.number().int().min(0),
  pendingIntents: z.record(command.nullable()),
  players: z.array(playerState).min(2).max(6),
  deck: z.array(cardId),
  deckCursor: z.number().int().min(0),
  discardPile: z.array(cardId),
  currentCardId: cardId.nullable(),
  timeline: z.object({
    year: z.number(),
    month: z.number().min(1).max(12),
    season: z.enum(['spring', 'summer', 'autumn', 'winter']),
    label: z.string(),
  }),
  ticker: z.array(z.string()),
  marketPrices: z.record(z.number()),
  businessMarket: z.object({
    openedRound: z.number().int().min(1),
    nextOpenRound: z.number().int().min(2),
    offerIds: z.array(z.enum([
      'micro-coffee', 'micro-kiosk', 'micro-studio', 'office', 'coffee',
      'logistics', 'storage', 'ai-startup', 'nft', 'laundromat', 'crypto-mining',
    ])).max(3),
  }),
  eventLog: z.array(gameEvent),
  version: z.number().int().min(1),
  activeInterestWindow: interestWindow.nullable().optional(),
  matchMode: z.enum(['classic', 'draft']).optional(),
  autoDeals: z.boolean().optional(),
  draftBoard: z.object({
    cards: z.array(cardId),
    claims: z.record(z.array(z.object({
      index: z.number().int().min(0),
      blind: z.boolean(),
      contestPref: z.enum(['fight', 'split']),
    }))),
    wonBy: z.record(playerId.nullable()),
    picked: z.record(z.boolean()),
    resolved: z.boolean(),
  }).nullable().optional(),
});
