export function getHostComment(
  personality: HostPersonality,
  event: keyof HostConfig['templates']
): string {
  const host = HOST_PERSONALITIES[personality];
  const templates = host.templates[event];
  return templates[Math.floor(Math.random() * templates.length)];
}

export function getRandomPersonality(): HostPersonality {
  const personalities: HostPersonality[] = ['judge', 'provocateur', 'joker', 'coach', 'broker'];
  return personalities[Math.floor(Math.random() * personalities.length)];
}
